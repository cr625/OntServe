class WolframCloudBackendError(RuntimeError):
    """Raised for configuration faults (missing library or credential)."""


class WolframCloudBackend:
    """
    Deterministic linguistic primitives evaluated in the Wolfram Cloud.

    Credentials are read from the environment, kept distinct from the AgentOne
    key so the two Wolfram paths fail independently:
        WOLFRAM_CLOUD_CONSUMER_KEY      consumer key of the Secured Auth Key
        WOLFRAM_CLOUD_CONSUMER_SECRET   consumer secret of the Secured Auth Key
    (Alternative single-key/APIFunction transport: WOLFRAM_CLOUD_API_KEY.)
    """

    def __init__(
        self,
        consumer_key: Optional[str] = None,
        consumer_secret: Optional[str] = None,
        timeout: int = 60,
    ):
        self.consumer_key = consumer_key or os.environ.get("WOLFRAM_CLOUD_CONSUMER_KEY", "")
        self.consumer_secret = consumer_secret or os.environ.get("WOLFRAM_CLOUD_CONSUMER_SECRET", "")
        self.timeout = timeout
        self._session = None  # lazily started WolframCloudSession

    # -- configuration ------------------------------------------------------

    @property
    def is_configured(self) -> bool:
        return bool(self.consumer_key and self.consumer_secret)

    def get_status(self) -> dict:
        return {
            "service": "Wolfram Cloud (deterministic backend)",
            "configured": self.is_configured,
            "timeout_seconds": self.timeout,
            "session_active": self._session is not None,
        }

    # -- session management -------------------------------------------------

    def _ensure_session(self):
        """Lazily create and start an authenticated cloud session. Raises a
        clear configuration error rather than degrading silently."""
        if self._session is not None:
            return self._session

        if not self.is_configured:
            raise WolframCloudBackendError(
                "Wolfram Cloud credentials missing: set WOLFRAM_CLOUD_CONSUMER_KEY "
                "and WOLFRAM_CLOUD_CONSUMER_SECRET."
            )

        try:
            from wolframclient.evaluation import (  # local import keeps the
                SecuredAuthenticationKey,           # module importable without
                WolframCloudSession,                # the optional dependency
            )
        except ImportError as exc:
            raise WolframCloudBackendError(
                "wolframclient is not installed. Add it to the OntServe venv: "
                "pip install wolframclient"
            ) from exc

        sak = SecuredAuthenticationKey(self.consumer_key, self.consumer_secret)
        session = WolframCloudSession(credentials=sak)
        session.start()
        if not session.authorized():
            raise WolframCloudBackendError("Wolfram Cloud session failed to authorize.")
        self._session = session
        return session

    def close(self):
        if self._session is not None:
            self._session.terminate()
            self._session = None

    def _evaluate(self, expr) -> Result[Any]:
        """Evaluate a Wolfram Language expression in the cloud and return the
        decoded Python value. `expr` is built with wolframclient.language.wl
        or wlexpr by the caller."""
        start = time.monotonic()
        try:
            session = self._ensure_session()
            value = session.evaluate(expr)
            elapsed = int((time.monotonic() - start) * 1000)
            logger.info("Wolfram Cloud evaluate ok in %dms", elapsed)
            return Result(success=True, data=value, elapsed_ms=elapsed)
        except WolframCloudBackendError:
            raise  # configuration faults propagate; not a per-call failure
        except Exception as exc:  # noqa: BLE001 - boundary: report, do not crash callers
            elapsed = int((time.monotonic() - start) * 1000)
            logger.error("Wolfram Cloud evaluate failed: %s", exc, exc_info=True)
            return Result(success=False, error=str(exc), elapsed_ms=elapsed)

