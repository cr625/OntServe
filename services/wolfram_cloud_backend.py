"""
Deterministic Wolfram Cloud backend for the ontology-supported language pipeline.

SKETCH. This is the structural skeleton specified in
`docs-internal/wolfram_linguistic_pipeline_design.md` (Section 4.2). It provides
the deterministic linguistic primitives that the AgentOne chat path
(`wolfram_service.py`) cannot: word-sense enumeration, lexical-relation
(hypernym) chains, and shallow predicate-argument structure. Results are typed,
not prose.

Separation of concerns:
    - wolfram_service.WolframService  -> AgentOne chat completions (prose).
    - wolfram_cloud_backend (this)    -> named Wolfram Language functions
                                         evaluated in the Wolfram Cloud,
                                         returning structured values.
The two paths fail independently and use independent credentials.

Authentication (open decision, see design doc Section 9):
    The Wolfram Client Library authenticates a cloud session with a Secured
    Authentication Key, a (consumer_key, consumer_secret) pair generated by
    GenerateSecuredAuthenticationKey[] in the Wolfram Language. That is the
    primary path implemented below. If the issued developer credential is
    instead a single bearer key tied to a deployed APIFunction, use the
    `_evaluate_via_api` transport stub instead of the session transport; the
    linguistic methods do not change.

Reference:
    https://reference.wolfram.com/language/workflow/ConnectPythonToTheWolframCloud.html
    https://wolframresearch.github.io/WolframClientForPython/

Per workspace policy: no silent fallbacks. A missing library, missing
credential, or failed evaluation surfaces as an explicit error (raised at
construction for configuration faults; returned in a structured Result for
per-call faults).
"""

