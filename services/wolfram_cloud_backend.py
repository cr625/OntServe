# ---------------------------------------------------------------------------
# Result wrapper and data contracts (design doc Section 6)
# ---------------------------------------------------------------------------


@dataclass
class Result(Generic[T]):
    """Per-call outcome. Structured failure rather than an exception across
    the boundary, matching the WolframService convention."""

    success: bool
    data: Optional[T] = None
    error: Optional[str] = None
    elapsed_ms: int = 0


@dataclass
class LexicalSense:
    """One sense of a term, from WordData. The `sense_id` is the stable
    WordNet-style key persisted by the Sense Registry."""

    term: str
    sense_id: str          # e.g. "report::noun::1" (document-submission sense)
    part_of_speech: str
    gloss: str
    rank: int = 0          # 0 = top-ranked candidate
    source: str = "WordData"


@dataclass
class HypernymChain:
    """Ordered superordinate terms for a chosen sense. Evidence for
    rdfs:subClassOf placement, never an authoritative assertion."""

    term: str
    sense_id: str
    parents: List[str] = field(default_factory=list)   # nearest first
    confidence: float = 0.0
    source: str = "WordData"


@dataclass
class FrameArgument:
    role: str              # grammatical/semantic role label
    span: str              # surface text of the argument


@dataclass
class ShallowFrameParse:
    """Predicate-argument approximation from TextStructure. The principled
    LTAG-frame parse reduces to this same shape (design doc Section 4.4)."""

    sentence: str
    predicate: str
    arguments: List[FrameArgument] = field(default_factory=list)
    negated: bool = False
    modality: Optional[str] = None     # e.g. "deontic" when a modal is present
    source: str = "TextStructure"


